#!/usr/bin/env python3
"""
build_task.py — turn a DeFiHackLabs PoC + verified on-chain source into a
self-contained, offline-replayable evmpatch task directory.

A task directory has this layout (see tasks/ngp_2025_09 for a real one):

    tasks/<task_id>/
    ├── task.json                 # metadata + hash-locks + allow-list (this file writes it)
    ├── project/                  # the Foundry project the agent edits
    │   ├── foundry.toml          #   [rpc_endpoints] alias -> ${TASK_RPC_URL}
    │   ├── remappings.txt
    │   ├── src/                  #   PATCHABLE source (verified on-chain source)
    │   └── lib/forge-std
    ├── tests/                    # HARNESS — hash-locked, copied in read-only at reward
    │   ├── poc.t.sol             #   exploit oracle: PASS on vuln, must FAIL on a fix
    │   └── hidden/
    │       ├── regression.t.sol  #   hand-written functionality invariants
    │       └── invariants_auto.t.sol  # AUTO-GENERATED compile + selector invariants
    ├── state/                    # frozen chain state for no-network replay
    │   ├── rpc_log.json          #   record/replay proxy log (superset: poc + hidden)
    │   ├── anvil_state.json      #   anvil_dumpState (optional / best-effort)
    │   └── rpc_cache/            #   Foundry RPC cache (FOUNDRY_OFFLINE fallback)
    └── reference_patch.sol.diff  # known-good fix; CI self-test only, NEVER shown to agent

BUILD PHASE (network available) — high level:
  1. Assemble project/ from verified source (fetch_sources.py output) + libs.
  2. Write poc.t.sol from the DeFiHackLabs PoC, rewired to the state-replay model:
       vm.createSelectFork(TASK_FORK_URL, block); vm.etch(victim, getDeployedCode(patchable))
     and an *exploit oracle* assertion (attacker profit > threshold) that FAILS post-fix.
  3. auto-generate tests/hidden/invariants_auto.t.sol from the ORIGINAL contract's
     public/external selectors (signature invariance) + a compile check.
  4. Warm the frozen state: run `rpc_replay.py record <rpc> state/rpc_log.json` and
     execute the WHOLE suite (poc + hidden) once so every slot either test touches is
     captured. (anvil --load-state is also attempted but is unreliable across chains —
     the record/replay proxy is the primary mechanism; see tasks/BUILD_LOG.md.)
  5. Emit task.json: metadata, temporal-split label, SHA-256 hash-locks of every harness
     file, and the allow-list of patchable source globs.

This module is import-safe (pure helpers) and also runnable as a CLI for step 3 & 5 on an
already-assembled task dir:  `python -m evmpatch_env.build_task finalize tasks/ngp_2025_09`
"""
from __future__ import annotations

