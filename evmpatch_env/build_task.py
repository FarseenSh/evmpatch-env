# --- temporal split (hard rule) -------------------------------------------------------
# Training: PoCs dated 2025-12 or earlier. Held-out TEST: 2026-03 .. 2026-08 (never train).
TRAIN_MAX = "2025-12"
TEST_RANGE = ("2026-03", "2026-08")


def split_for_month(month: str) -> str:
    """month is 'YYYY-MM'. Returns 'train', 'test', or 'excluded'."""
    if month <= TRAIN_MAX:
        return "train"
    if TEST_RANGE[0] <= month <= TEST_RANGE[1]:
        return "test"
    # 2026-01/02 fall in neither bucket — quarantine rather than silently train on them.
    return "excluded"


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    h.update(path.read_bytes())
    return h.hexdigest()


def hash_lock_dir(root: Path, rel_globs: list[str]) -> dict[str, str]:
    """SHA-256 every file matched by rel_globs, keyed by path relative to root."""
    locks: dict[str, str] = {}
    for g in rel_globs:
        for p in sorted(root.glob(g)):
            if p.is_file():
                locks[str(p.relative_to(root))] = sha256_file(p)
    return locks


def contract_selectors(project_dir: Path, contract_ref: str) -> dict[str, str]:
    """methodIdentifiers of a contract via `forge inspect`. contract_ref e.g. 'Token.sol:Token'."""
    out = subprocess.run(
        ["forge", "inspect", contract_ref, "methodIdentifiers", "--json"],
        cwd=project_dir, capture_output=True, text=True,
    )
    if out.returncode != 0:
        raise RuntimeError(f"forge inspect failed: {out.stderr[-400:]}")
    return json.loads(out.stdout or "{}")


# --- auto-generated hidden invariant test ---------------------------------------------
AUTO_HEADER = """// SPDX-License-Identifier: UNLICENSED
pragma solidity ^0.8.20;

// HARNESS FILE — hash-locked, read-only. *** AUTO-GENERATED by build_task.py — DO NOT EDIT ***
// Signature-invariance + compile invariants: a valid patch may change the *body* of the
// vulnerable contract but must not delete or re-type its public/external ABI, and the
// project must still compile (implicit: getDeployedCode below reverts if it does not).
// These PASS on both the vulnerable and a correctly-patched contract; a "delete the
// function" or "brick the contract" shortcut trips them and scores 0.
//
// The selector check reads the dispatch table itself rather than a proxy for it such as
// `VICTIM.code.length > 0` (true for any non-empty contract, so it would prove nothing).
// It walks the runtime bytecode as EVM code (skipping PUSH immediates so a selector cannot
// be forged by data that merely looks like an opcode) and records every PUSH4 immediate.
// Solidity emits the dispatch table as
// `PUSH4 <selector>; EQ; PUSH2 <dest>; JUMPI`, so a selector that is absent from that set
// is absent from the ABI. `test_selector_check_is_not_vacuous` asserts a selector that
// cannot be in the table is reported absent, so the check cannot silently degrade to
// always-true.
//
// A PUSH4 immediate is NECESSARY but not SUFFICIENT (it could be dead data, and a proxy or
// catch-all fallback could dispatch selectors that are not in the table at all). So there is
// a SECOND, behavioural check: `test_abi_selectors_dispatch` actually CALLS every required
// function with well-formed zero-valued calldata and asserts the contract does not answer
// with the "no such function" signature (failure + empty returndata, i.e. the dispatcher's
// `revert(0,0)`). `test_unknown_selector_is_rejected` is its control: an impossible selector
// MUST produce that signature, which is what makes the behavioural check meaningful. The
// grade records both checks separately (RewardResult.abi_invariants).
//
// The bytecode half is deliberately CONSERVATIVE in the accept direction: PUSH1..PUSH4 are
// all indexed because solc strips leading zero bytes from push constants, so a small
// constant can coincide with a selector that has leading zero bytes. That can only produce
// a false "present", never a false "absent" -- and the behavioural half is what closes that
// gap, since a selector that is merely present as data will not dispatch.
"""


def _top_level_arg_count(sig: str) -> int:
    """Number of top-level ABI parameters in a signature like `f(uint256,(a,b)[],bool)`."""
    inner = sig[sig.index("(") + 1: sig.rindex(")")]
    if not inner.strip():
        return 0
    depth, n = 0, 1
    for ch in inner:
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif ch == "," and depth == 0:
            n += 1
    return n


def render_auto_invariants(victim_addr: str, selectors: dict, block: int,
                           artifact_ref: str = "Token.sol:Token") -> str:
    checks, dispatch, calibrate = [], [], []
    for sig, sel in sorted(selectors.items(), key=lambda kv: kv[1]):
        n = _top_level_arg_count(sig)
        checks.append(f'        _assertHasSelector(hex"{sel}", "{sig}");')
        dispatch.append(f'        _assertSelectorDispatches(hex"{sel}", {n}, "{sig}");')
        calibrate.append(f'        _note(hex"{sel}", {n});')
    checks_block = "\n".join(checks)
    dispatch_block = "\n".join(dispatch)
    calibrate_block = "\n".join(calibrate)
    return f"""{AUTO_HEADER}
import "forge-std/Test.sol";

contract AutoInvariants is Test {{
    address constant VICTIM = {victim_addr};
    uint256 constant FORK_BLOCK = {block};

    // every PUSH1..PUSH4 immediate found in the victim's runtime bytecode
    mapping(bytes4 => bool) internal push4;
    uint256 internal push4Count;
    // which selectors the ORIGINAL deployed contract answers under a zero-argument probe
    mapping(bytes4 => bool) internal originalDispatches;
    uint256 internal calibratedCount;
    uint256 internal excludedCount;

    function setUp() public {{
        string memory url = vm.envOr("TASK_FORK_URL", string("bsc"));
        try vm.createSelectFork(url, FORK_BLOCK) {{ }} catch {{ vm.createSelectFork(url); }}

        // CALIBRATE FIRST, against the contract that is actually deployed on the fork.
        // The dispatch probe's "no such function" signature (call fails, no returndata) is
        // also what a function produces when it reverts with no reason -- e.g. a call into
        // a zero address argument. Recording which selectors the ORIGINAL contract answers
        // turns the check into the property we actually want: every selector the deployed
        // contract dispatches must still be dispatched after the patch. Selectors the
        // original itself cannot answer under a zero-argument probe are excluded and
        // counted, so the exclusion is visible rather than silent.
        _calibrate();

        // getDeployedCode compiles the patchable source; if the patch breaks compilation
        // this reverts and every invariant below fails -> reward 0 (compile gate).
        vm.etch(VICTIM, vm.getDeployedCode("{artifact_ref}"));
        _indexPush4(VICTIM.code);
    }}

    /// @dev Linear EVM code walk. The immediate of every PUSHn is skipped rather than
    ///      rescanned, so a selector-shaped run of bytes inside (say) a PUSH32 constant is
    ///      NOT counted. PUSH1..PUSH4 are all indexed, not just PUSH4: solc strips leading
    ///      zero bytes from push constants, so a selector like balanceOf(address,uint256)
    ///      = 0x00fdd58e is emitted as `PUSH3 0xfdd58e`. Zero is never indexed (it is not a
    ///      real selector and PUSH1 0x00 is everywhere).
    function _indexPush4(bytes memory code) internal {{
        uint256 i = 0;
        uint256 n = code.length;
        while (i < n) {{
            uint8 op = uint8(code[i]);
            if (op >= 0x60 && op <= 0x63) {{            // PUSH1..PUSH4
                uint256 width = uint256(op) - 0x5f;
                if (i + width < n) {{
                    uint32 v = 0;
                    for (uint256 k = 1; k <= width; k++) {{
                        v = (v << 8) | uint32(uint8(code[i + k]));
                    }}
                    if (v != 0) {{
                        bytes4 sel = bytes4(v);
                        if (!push4[sel]) {{ push4[sel] = true; push4Count++; }}
                    }}
                }}
            }}
            if (op >= 0x60 && op <= 0x7f) {{     // PUSH1..PUSH32: skip the immediate
                i += 1 + (uint256(op) - 0x5f);
            }} else {{
                i += 1;
            }}
        }}
    }}

    function _assertHasSelector(bytes4 sel, string memory sig) internal view {{
        assertTrue(push4[sel],
            string.concat("ABI broken: selector absent from runtime bytecode: ", sig));
    }}

    function test_abi_selectors_preserved() public view {{
{checks_block}
    }}

    // ---------------------------------------------------------------- behavioural check
    // A PUSH4 immediate proves the bytes are there; it does not prove the contract answers
    // the call. Probe every required function with well-formed, zero-valued calldata (one
    // 32-byte word per top-level parameter, which decodes to zeros for value types and to
    // empty for dynamic ones) and reject the dispatcher's "no such function" signature.

    /// @dev The "no such function" answer of a Solidity dispatcher is `revert(0, 0)`: the
    ///      call FAILS and returns NO data. Anything else -- success, a require string, a
    ///      custom error -- means the function exists and ran.
    function _probe(bytes4 sel, uint256 nargs) internal returns (bool ok, uint256 retlen) {{
        bytes memory data = abi.encodePacked(sel, new bytes(32 * nargs));
        bytes memory ret;
        (ok, ret) = VICTIM.call{{gas: 3000000}}(data);
        retlen = ret.length;
    }}

    function _dispatches(bytes4 sel, uint256 nargs) internal returns (bool) {{
        (bool ok, uint256 retlen) = _probe(sel, nargs);
        return ok || retlen > 0;   // anything but the dispatcher's bare revert(0, 0)
    }}

    function _calibrate() internal {{
{calibrate_block}
    }}

    function _note(bytes4 sel, uint256 nargs) internal {{
        if (_dispatches(sel, nargs)) {{
            originalDispatches[sel] = true;
            calibratedCount++;
        }} else {{
            excludedCount++;
        }}
    }}

    function _assertSelectorDispatches(bytes4 sel, uint256 nargs, string memory sig) internal {{
        if (!originalDispatches[sel]) {{
            return;   // the deployed contract could not answer this probe either
        }}
        assertTrue(_dispatches(sel, nargs),
            string.concat("ABI broken: contract does not dispatch ", sig));
    }}

    /// Control for the probe above. An impossible selector MUST get the "no such function"
    /// answer; if it does not, the contract has a catch-all fallback and dispatch probing
    /// proves nothing, so the whole behavioural check is void and must fail loudly.
    function test_unknown_selector_is_rejected() public {{
        (bool ok, uint256 retlen) = _probe(bytes4(hex"deadf00d"), 0);
        assertFalse(ok, "impossible selector accepted: catch-all fallback, dispatch probe meaningless");
        assertEq(retlen, 0, "impossible selector returned data: dispatch probe meaningless");
    }}

    function test_abi_selectors_dispatch() public {{
        assertGt(calibratedCount, 0,
            "calibration answered nothing: the behavioural ABI check has no baseline");
{dispatch_block}
    }}

    /// The selector check must be able to say NO. A selector that no compiler would emit
    /// into this dispatch table must be reported absent; if this fails, the check above
    /// has degenerated into a tautology and every ABI result from it is worthless.
    function test_selector_check_is_not_vacuous() public view {{
        assertGt(push4Count, 0, "no PUSH4 immediates indexed: the code walk is broken");
        assertFalse(push4[bytes4(hex"deadf00d")], "vacuous selector check: bogus selector reported present");
        assertFalse(push4[bytes4(hex"00000000")], "vacuous selector check: zero selector reported present");
    }}

    function test_contract_has_code() public view {{
        assertGt(VICTIM.code.length, 0, "patched contract has no deployed code");
    }}
}}
"""



# --- project scaffolding --------------------------------------------------------------
DEFAULT_REMAPPINGS = "forge-std/=lib/forge-std/src/\n"


def foundry_toml(solc: str | None = None, optimizer: bool = True, runs: int = 200,
                 evm_version: str = "shanghai", rpc_alias: str = "chain") -> str:
    """The project's foundry.toml. Pin the compiler to the settings the contract was
    VERIFIED with wherever possible: the grader etches code compiled from this project
    onto the live forked address, so a different compiler is a different contract.
    Leave `solc` unset only when the project mixes major Solidity versions (an old victim
    contract plus modern forge-std), where Foundry must pick per file."""
    pin = f"solc = '{solc}'\n" if solc else ""
    return (
        "[profile.default]\n"
        "src = 'src'\ntest = 'test'\nout = 'out'\nlibs = ['lib']\n"
        f"{pin}"
        f"evm_version = '{evm_version}'\n"
        f"optimizer = {str(optimizer).lower()}\n"
        f"optimizer_runs = {runs}\n"
        'fs_permissions = [{ access = "read", path = "./" }]\n'
        "\n[rpc_endpoints]\n"
        f'{rpc_alias} = "${{TASK_RPC_URL}}"\n'
    )


def scaffold_project(task_dir: Path, src_files: dict, toml: str,
                     forge_std_from: Path, remappings: str = DEFAULT_REMAPPINGS) -> Path:
    """Create tasks/<id>/{project,tests/hidden,state} and drop the patchable source in.

    src_files maps a project-relative path ("src/contracts/Token.sol") to file content.
    forge_std_from points at an existing `lib/forge-std` to copy, so a task directory is
    self-contained and does not need `forge install` (and therefore no network) to build.
    """
    task_dir = Path(task_dir)
    project = task_dir / "project"
    for d in (project / "src" / "contracts", project / "lib",
              task_dir / "tests" / "hidden", task_dir / "state"):
        d.mkdir(parents=True, exist_ok=True)
    (project / "foundry.toml").write_text(toml)
    (project / "remappings.txt").write_text(remappings)
    dst = project / "lib" / "forge-std"
    if not dst.exists():
        shutil.copytree(forge_std_from, dst)
    for rel, content in src_files.items():
        f = project / rel
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(content)
    return task_dir


# --- expected-test manifest -----------------------------------------------------------
# The scorer refuses to award `solved` unless the set of test ids that actually executed
# is EXACTLY the set this file declares. Without it, "some tests passed and none failed"
# was enough — which a partial suite, an unrelated test, or a crashed runner all satisfy.
MANIFEST_ID_FORMAT = "<test file path>:<contract>:<function signature>"


def list_executed_test_ids(workdir: Path, match_path: str, fork_url: str) -> list[str]:
    """Fully qualified ids of the tests forge actually ran for `match_path`.

    Derived from a real `forge test --json` report rather than from `--list`, because the
    report is what the grader compares against and only the report carries the exact
    `fn(argtypes)` spelling that fuzz/parameterised tests produce.
    """
    import os
    env = dict(os.environ)
    env.update({"TASK_FORK_URL": fork_url, "FOUNDRY_OFFLINE": "true",
                "FOUNDRY_NO_STORAGE_CACHING": "true", "NO_COLOR": "1"})
    out = subprocess.run(["forge", "test", "--match-path", match_path, "--json"],
                         cwd=workdir, capture_output=True, text=True, env=env)
    try:
        blob = json.loads(out.stdout.strip())
    except Exception as exc:
        raise RuntimeError(f"forge --json report unparseable for {match_path}: {exc}\n"
                           f"{out.stdout[-800:]}\n{out.stderr[-400:]}")
    ids = []
    for suite, sdata in blob.items():
        for fn, tdata in (sdata.get("test_results") or {}).items():
            if fn.startswith("setUp("):
                raise RuntimeError(f"{suite} setUp() failed while building the manifest: "
                                   f"{tdata.get('reason')}")
            ids.append(f"{suite}:{fn}")
    return sorted(ids)


def build_manifest_offline(task_dir: Path, exploit_oracle_fn: str = "testExploit()",
                           accepted_block_kinds: list[str] | None = None,
                           patch_rel: str = "src/contracts/Token.sol") -> dict:
    """Derive tests/manifest.json by running the WHOLE suite against the task's own frozen
    state (offline, via the fail-closed replay proxy) and reading forge's --json report.

    Deriving it from a real run rather than from a static list means the manifest can only
    ever name tests that actually execute under the exact conditions the grader uses.
    """
    import shutil as _shutil
    import tempfile as _tempfile
    import uuid as _uuid
    from . import sandbox

    task_dir = Path(task_dir)
    root = Path(_tempfile.gettempdir()) / f"evmpatch_manifest_{_uuid.uuid4().hex}"
    root.mkdir(parents=True, exist_ok=True)
    work = root / "work"
    port_file, miss_file = root / "proxy.port", root / "rpc_misses.json"
    proxy = subprocess.Popen(
        [sys.executable, str(sandbox.RPC_REPLAY), "replay",
         str(task_dir / "state" / "rpc_log.json"), "0",
         "--port-file", str(port_file), "--miss-file", str(miss_file)],
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    try:
        bound = sandbox._await_proxy(proxy, port_file, deadline_s=20.0)
        if bound is None:
            raise RuntimeError("replay proxy did not bind while building the manifest")
        sandbox.assemble_workdir(task_dir, None, work)
        url = f"http://127.0.0.1:{bound}"
        poc_ids = list_executed_test_ids(work, "test/poc.t.sol", url)
        hidden_ids = list_executed_test_ids(work, "test/hidden/*", url)
        observed = observed_block_reason(task_dir, url, work, exploit_oracle_fn, patch_rel)
    finally:
        proxy.terminate()
        try:
            proxy.wait(timeout=5)
        except Exception:
            proxy.kill()
        _shutil.rmtree(root, ignore_errors=True)

    oracle = [i for i in poc_ids if i.endswith(":" + exploit_oracle_fn)]
    if len(oracle) != 1:
        raise RuntimeError(f"expected exactly one {exploit_oracle_fn} among {poc_ids}")
    reasons = ["*assertion failed*", "*exploit did not yield profit*"]
    if observed and observed not in reasons:
        reasons.append(observed)
    print(f"[build_task] recognised 'exploit blocked' reasons: {reasons}")
    return write_manifest(task_dir, poc_ids, hidden_ids, oracle[0], accepted_block_kinds,
                          recognised_block_reasons=reasons)


def apply_unified_diff(original: str, diff_text: str) -> str:
    """Apply a single-file unified diff. Deliberately tiny and dependency-free (CI does not
    need GNU patch); every context and removal line is verified before anything is written."""
    lines = original.splitlines(keepends=True)
    diff_lines = diff_text.splitlines(keepends=True)
    offsets, pos = [], 0
    for ln in diff_lines:
        offsets.append(pos)
        pos += len(ln)
    starts = [(m.start(), m) for m in
              re.finditer(r"^@@ -(\d+)(?:,\d+)? \+\d+(?:,\d+)? @@.*$", diff_text, re.M)]
    if not starts:
        raise ValueError("no hunks in diff")
    out, src = [], 0
    for idx, (offset, m) in enumerate(starts):
        first = int(m.group(1)) - 1
        body_start = offsets.index(offset) + 1
        body_end = offsets.index(starts[idx + 1][0]) if idx + 1 < len(starts) else len(diff_lines)
        out.extend(lines[src:first])
        src = first
        for raw in diff_lines[body_start:body_end]:
            if raw.startswith("\\"):                     # "\ No newline at end of file"
                continue
            tag, text = raw[:1], raw[1:]
            if tag == " ":
                if lines[src] != text:
                    raise ValueError(f"diff context mismatch at line {src + 1}")
                out.append(lines[src]); src += 1
            elif tag == "-":
                if lines[src] != text:
                    raise ValueError(f"diff removal mismatch at line {src + 1}")
                src += 1
            elif tag == "+":
                out.append(text)
            else:
                raise ValueError(f"unexpected diff line: {raw!r}")
    out.extend(lines[src:])
    return "".join(out)


def observed_block_reason(task_dir: Path, fork_url: str, work: Path, oracle_fn: str,
                          patch_rel: str) -> str | None:
    """Run the PoC against the REFERENCE patch and report why the exploit oracle failed.

    That reason string is what the task then declares as a recognised "exploit blocked"
    signal. Anything else the grader sees later is `unrecognised_failure` -> inconclusive,
    so a PoC that starts failing for a NEW reason gets a human, not a reward.
    """
    diff_path = task_dir / "reference_patch.sol.diff"
    if not diff_path.exists():
        return None
    target = work / patch_rel
    original = target.read_text()
    try:
        target.write_text(apply_unified_diff(original, diff_path.read_text()))
        from . import sandbox
        run, _ = sandbox._run_forge(work, "test/poc.t.sol", fork_url, 600)
        hit = [t for t in run.tests.values() if t.name == oracle_fn]
        if len(hit) == 1 and hit[0].status == "Failure":
            return hit[0].reason
        return None
    finally:
        target.write_text(original)


def write_manifest(task_dir: Path, poc_ids: list[str], hidden_ids: list[str],
                   exploit_oracle: str,
                   accepted_block_kinds: list[str] | None = None,
                   recognised_block_reasons: list[str] | None = None) -> dict:
    """Emit tests/manifest.json — the expected-test contract for one task."""
    if exploit_oracle not in poc_ids:
        raise ValueError(f"exploit oracle {exploit_oracle!r} not among the PoC tests {poc_ids}")
    manifest = {
        "version": 1,
        "id_format": MANIFEST_ID_FORMAT,
        "poc": {
            "exploit_oracle": exploit_oracle,
            "tests": sorted(poc_ids),
            "count": len(poc_ids),
            # A failing oracle only counts as "exploit blocked" when it failed in the test
            # BODY. "assertion" = the profit assertion tripped; "revert" = the exploit path
            # itself reverted (e.g. the flash loan can no longer be repaid). Infrastructure
            # failures are never accepted; tighten to ["assertion"] for a task whose PoC
            # should always reach its assertion.
            "accepted_block_kinds": accepted_block_kinds or ["assertion", "revert"],
            # fnmatch patterns. A failing oracle whose reason matches NONE of these is
            # `unrecognised_failure` -> inconclusive, never a reward. The concrete revert
            # string is observed from a real run of reference_patch.sol.diff at build time.
            "recognised_block_reasons": recognised_block_reasons or ["*assertion failed*"],
        },
        "hidden": {"tests": sorted(hidden_ids), "count": len(hidden_ids)},
    }
    (task_dir / "tests" / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    return manifest


